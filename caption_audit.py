"""Caption-sense audit: does the text a clip ships with actually read like
a sentence a viewer can follow?

Word timestamps made cuts land in a pause, which is a different thing from
landing in a *sentence*. A clip can start cleanly on the word "because" and
stop cleanly on "the" and still be nonsense — and Whisper, left alone in a
music bed or a cough, produces loops ("Thank you. Thank you. Thank you.") and
consonant mush that renders as a caption and gets shipped anyway. Until now
nothing between the transcript and the burn checked for that:
``auto_caption_clip`` only asked whether *any* word fell in the range.

Two jobs, kept separate so each can be tested without ffmpeg:

  1. ``review()`` — measure the blocks the renderer is about to draw and return
     a verdict. Never mutates anything; the caller decides what to do.
  2. ``repair_range()`` — move a clip's cut onto the nearest real sentence
     boundary, inside the duration band, before anything is rendered.

Everything here is pure and never raises on bad input: a caption verdict is
editorial advice, not a gate. An audit that can break a job would be worse
than no audit, for the same reason ``auto_caption_clip`` swallows every
exception (a caption problem must never cost the user the clip they paid for).
"""

import os
import re

# Reading speed ceiling for a caption, in characters per second. Typical adult
# silent reading is 15-20 cps; a short-form viewer re-reading a line while a
# cut moves is under 15. Blocks above this are on screen for less time than
# they take to parse, which reads as "the captions don't match the video" even
# when every word is correct.
MAX_READ_CPS = 22.0

# Speech below this many words per second over a whole clip is almost never a
# person talking: it is a music bed, applause, or a Whisper run on noise. A
# real conversation runs 2.0-3.5 words/second, and even a slow monologue
# stays above 1.2.
MIN_WORDS_PER_SEC = 0.5

# And above this many it is not speech either — nobody articulates 8 words a
# second for a whole clip. This is the signature of a transcript whose chunks
# were stacked on top of each other (the ASR offset bug: 27k words landing in
# the first ten minutes), which captions as fluent nonsense. Cheaper and more
# honest than any model call: the arithmetic says the audio cannot contain it.
MAX_WORDS_PER_SEC = 8.0

# A block shown for less than this is an interjection ("Huh?", "Go!") whose
# instantaneous chars/second is meaningless; judging it would flag most of a
# real karaoke caption track.
MIN_BLOCK_SECONDS = 0.12

# A single caption word with no vowel and no digit is a hallucination
# artefact ("hh", "tk", "ng"), not a word in any language Whisper knows.
GIBBERISH_VOWELS = "aeiouyàáâäãåèéêëìíîïòóôöõùúûüæœ"

# Below this vowel share a 3+ letter token is mush. Real English words sit at
# 0.3-0.5 even when terse ("the" 0.33, "strengths" 0.14 is the famous
# exception, hence the >= 3 letter gate plus a ratio, not a zero test).
GIBBERISH_VOWEL_FLOOR = 0.18

# boilerplate Whisper invents at the tail of podcasts, streams and YouTube
# uploads. These are real sentences — that is what makes them dangerous: they
# pass every grammatical check and still caption a clip about nothing.
JUNK_PATTERNS = (
    r"\blike and subscribe\b",
    r"\bsubscribe to (my|this|the) channel\b",
    r"\bthanks?\b.*\bwatching\b",
    r"\bplease give this video a like\b",
    r"\bcaptioning by \w+\b",
    r"\bamara\.org\b",
    r"\bgenerated by (voice|automatic)\b",
)

_SENTENCE_TERM = ".!?"
_SENTENCE_CLOSE = "\"')]"


def enabled():
    """Whether the audit runs (CAPTION_AUDIT=0 turns it off).

    Off-switches matter here: the repair moves cut times, and an operator
    debugging a boundary problem needs the pipeline to stop touching them.
    """
    return os.environ.get("CAPTION_AUDIT", "1").strip() != "0"


def _clean(text):
    return " ".join(str(text or "").split())


def _repeat_key(line):
    """The identity a repeat is counted under: case- and punctuation-folded."""
    return _clean(line).lower().strip(_SENTENCE_CLOSE).rstrip(".!?, ").strip()


def _longest_repeat_run(lines):
    """(line, how many times it appeared back-to-back) for the longest run.

    Adjacency is the whole point: "never mind" five times in a row is the
    transcript stalling on non-speech, while "you" five times across a minute
    is someone talking.
    """
    best_line, best_run, run = ("", 0), 0, 0
    previous = None
    for line in lines:
        key = _repeat_key(line)
        run = run + 1 if key and key == previous else 1
        previous = key
        if run > best_run:
            best_run, best_line = run, key
    return best_line, max(best_run, 1 if lines else 0)


def ends_sentence(text):
    """True when ``text`` closes a sentence, ignoring trailing quotes/brackets.

    "go." / "go.\"" / "now!" all close; "go" and "the" do not. The trailing
    closer matters because Whisper attaches the closing quote to the word, so
    a strict ``endswith('.')`` check misses the most common boundary there is:
    somebody finishing a quoted line.
    """
    t = _clean(text).rstrip(_SENTENCE_CLOSE).rstrip()
    return bool(t) and t[-1] in _SENTENCE_TERM


def starts_sentence(text):
    """True when ``text`` plausibly opens a sentence.

    Uppercase-initial, or a digit, or a quote/bracket leading into one. A
    lowercase start is only mid-sentence if something was said before it, so
    callers pass the clip's first words and the surrounding context, not a
    bare token.
    """
    t = _clean(text).lstrip(_SENTENCE_CLOSE)
    if not t:
        return False
    if t[0].isdigit() or t[0] in "\"'([{":
        return True
    return t[0].isupper()


def _letters(text):
    return re.sub(r"[^a-zA-Zà-ÿœ]", "", str(text or ""))


def vowel_ratio(word):
    """Share of a token's letters that are vowels (0.0 when it has none)."""
    letters = _letters(word).lower()
    if not letters:
        return 0.0
    hits = sum(1 for ch in letters if ch in GIBBERISH_VOWELS)
    return hits / len(letters)


def join_words(words):
    """The caption line a list of block words renders as."""
    return " ".join(_clean(w.get("word")) for w in words if _clean(w.get("word")))


def flatten_words(transcript):
    """Every spoken word of the whole transcript, absolute times, sorted.

    Continuation fragments merge first, the same way the renderer does it, so a
    hyphenated "You" + "-Tube" is one token here and one token on screen. That
    means the leading space faster-whisper uses to mark a boundary has to
    survive this far; it is stripped only AFTER merging, because display text
    has no business carrying it. Returns [] for anything that isn't a
    transcript dict.
    """
    if not isinstance(transcript, dict):
        return []
    try:
        import subtitles as _subs
    except Exception:
        return []
    raw = []
    for segment in (transcript.get("segments") or []):
        for word in (segment or {}).get("words") or []:
            if not isinstance(word, dict):
                continue
            text = str(word.get("word") or "")
            if not text.strip():
                continue
            raw.append({"word": text,
                        "start": float(word.get("start") or 0.0),
                        "end": float(word.get("end") or 0.0)})
    try:
        raw = _subs.merge_continuation_words(raw)
    except Exception:
        pass
    out = [{"word": _clean(w["word"]), "start": w["start"], "end": w["end"]}
           for w in raw]
    out = [w for w in out if w["word"]]
    out.sort(key=lambda w: (w["start"], w["end"]))
    return out


def _context(transcript_words, clip_start, clip_end):
    """(text before the clip, text after it), a sentence worth each.

    Enough to tell "the clip opens mid-sentence" from "the speaker started a
    new sentence": for that, only the last words before the cut and the first
    few after it are needed.
    """
    before = [w["word"] for w in transcript_words if w["end"] <= clip_start]
    after = [w["word"] for w in transcript_words if w["start"] >= clip_end]
    return " ".join(before[-12:]), " ".join(after[:12])


def review(blocks, text_before="", text_after="", clip_seconds=0.0,
           karaoke=False):
    """Judge the caption blocks a clip would ship with.

    blocks: the renderer's own word blocks — list of lists of
      {'word','start','end'} with clip-relative times (what
      ``subtitles._collect_word_blocks`` returns).
    text_before / text_after: the spoken words just outside the cut, used only
      for the two mid-sentence verdicts; pass "" when unknown and the check
      stays quiet rather than guessing.
    clip_seconds: the clip's real length, used for the sparse-speech ratio.
    karaoke: the renderer reveals one word at a time (the default template).
      Then a block's own duration is the SPEAKING speed, not the reading time,
      and a two-word block flashed for 0.3 s is not a caption defect — the
      viewer hears it that fast. Only the clip's total text load and real walls
      of text count.

    Returns {"ok", "issues", "text", "stats"}. ``issues`` is a list of
    {"code", "detail", "fixable"} — codes are stable strings, safe to key UI
    and metadata on. ``ok`` is False when anything was flagged.
    """
    issues = []
    blocks = [b for b in (blocks or []) if b]
    lines = [join_words(b) for b in blocks]
    lines = [l for l in lines if l]
    text = " ".join(lines)
    words = [w for b in blocks for w in b if _clean(w.get("word"))]

    stats = {
        "blocks": len(blocks),
        "words": len(words),
        "chars_per_sec": 0.0,
        "words_per_sec": 0.0,
    }

    if not blocks or not words:
        issues.append({"code": "no_speech",
                       "detail": "no captioned words fall inside the clip",
                       "fixable": False})
        return {"ok": False, "issues": issues, "text": "", "stats": stats}

    span = clip_seconds
    if not span and blocks:
        span = float(blocks[-1][-1].get("end") or 0.0)
    span = max(float(span or 0.0), 0.001)
    chars = len(text.replace(" ", ""))
    stats["chars_per_sec"] = round(chars / span, 2)
    stats["words_per_sec"] = round(len(words) / span, 2)

    # Openings. First token lowercase AND the words before the cut did not
    # close a sentence: the clip starts mid-thought.
    first = words[0]["word"]
    if text_before and not starts_sentence(first) and not ends_sentence(text_before):
        issues.append({"code": "opens_mid_sentence",
                       "detail": f"starts on \"{first}\", "
                                 f"right after \"...{text_before[-40:]}\"",
                       "fixable": True})

    # Endings. Mirror of the opening: last token is not a terminator and the
    # speech after the cut continues the same sentence.
    last = words[-1]["word"]
    if text_after and not ends_sentence(last) and not starts_sentence(text_after):
        issues.append({"code": "ends_mid_sentence",
                       "detail": f"cuts on \"{last}\", "
                                 f"then \"{text_after[:40]}...\"",
                       "fixable": True})

    # Hallucination loops: the SAME phrase three or more times IN A ROW. Not
    # "the word 'you' appears five times in 90 seconds" — shouting a filler
    # word is normal speech, and a run test that ignores adjacency turns every
    # energetic clip into a false positive.
    loop_line, loop_run = _longest_repeat_run(lines)
    if loop_run >= 3 and len(loop_line.split()) >= 2 and len(loop_line) >= 8:
        issues.append({"code": "repeated_text",
                       "detail": f"\"{loop_line}\" captioned {loop_run} times in "
                                 "a row — ASR loop, not speech",
                       "fixable": False})
    elif loop_run >= 4:
        # Long enough a line to repeat identically four times even as a single
        # word ("no no no no no") is still a stall in the audio.
        issues.append({"code": "repeated_text",
                       "detail": f"\"{loop_line}\" captioned {loop_run} times in a row",
                       "fixable": False})

    # Unreadable pacing. Two different questions, and the style decides which
    # one is real:
    #   • whole-clip load — can the viewer keep up with this caption track at
    #     all? Measured in characters per second of video, and it applies to
    #     every style. Live numbers on real clips run 7-12 cps; above the
    #     ceiling the text is a firehose no one reads.
    #   • one block shown too briefly to parse. Only meaningful when the block
    #     is displayed AT ONCE (classic). Karaoke reveals a word as it is
    #     spoken, so a 2-word block lasting 0.3 s is the speaker being fast,
    #     not the caption being broken — flagging those put a false warning on
    #     every energetic clip (measured on a live job: 4 of 22 blocks).
    if stats["chars_per_sec"] > MAX_READ_CPS:
        issues.append({"code": "too_fast_to_read",
                       "detail": f"{stats['chars_per_sec']:.0f} chars/sec across "
                                 f"{span:.0f}s — above the {MAX_READ_CPS:.0f} "
                                 "chars/sec a viewer can read",
                       "fixable": True})
    elif not karaoke:
        fast = [b for b in blocks
                if (b[-1].get("end") or 0.0) - (b[0].get("start") or 0.0) >= MIN_BLOCK_SECONDS
                and len(join_words(b).replace(" ", "")) >= 10
                and len(join_words(b).replace(" ", "")) /
                    ((b[-1]["end"] - b[0]["start"]) or 1) > MAX_READ_CPS]
        if fast:
            worst = max(fast, key=lambda b: len(join_words(b)))
            issues.append({"code": "too_fast_to_read",
                           "detail": f"{len(fast)}/{len(blocks)} blocks exceed "
                                     f"{MAX_READ_CPS:.0f} chars/sec, e.g. "
                                     f"\"{join_words(worst)[:40]}\"",
                           "fixable": True})

    # Barely any speech: the "audio" is music, applause, or a long pause the
    # cut included anyway.
    if stats["words_per_sec"] < MIN_WORDS_PER_SEC:
        issues.append({"code": "sparse_speech",
                       "detail": f"{stats['words_per_sec']:.1f} words/sec over "
                                 f"{span:.0f}s — little real speech in range",
                       "fixable": False})
    elif stats["words_per_sec"] > MAX_WORDS_PER_SEC:
        # The mirror image, and the one that silently shipped broken captions
        # for weeks: transcript chunks stacked on the same seconds. Every word
        # is real, the sentence shape is fine, and the audio cannot contain it.
        issues.append({"code": "impossible_density",
                       "detail": f"{stats['words_per_sec']:.1f} words/sec over "
                                 f"{span:.0f}s ({stats['words']} words) — more "
                                 "speech than this clip can hold; the "
                                 "transcript is misaligned, re-transcribe",
                       "fixable": False})

    # Consonant mush. Counted over tokens that are pure letters, because
    # punctuation-only tokens ("—", "\"") are normal.
    letters_words = [w for w in words if _letters(w["word"])]
    if letters_words:
        mush = [w for w in letters_words
                if len(_letters(w["word"])) >= 3
                and vowel_ratio(w["word"]) < GIBBERISH_VOWEL_FLOOR]
        if len(mush) / len(letters_words) > 0.3:
            issues.append({"code": "gibberish",
                           "detail": f"{len(mush)}/{len(letters_words)} tokens "
                                     f"have no vowels, e.g. "
                                     f"\"{' '.join(w['word'] for w in mush[:4])}\"",
                           "fixable": False})

    # ASR boilerplate at the head or tail of the clip.
    for pattern in JUNK_PATTERNS:
        m = re.search(pattern, text.lower())
        if m:
            issues.append({"code": "junk_text",
                           "detail": f"ASR boilerplate: \"{m.group(0)}\"",
                           "fixable": True})
            break

    return {"ok": not issues, "issues": issues, "text": text, "stats": stats}


def audit(transcript, clip_start, clip_end, max_chars=20, max_duration=2.0,
          karaoke=False):
    """Review exactly what this clip would be captioned with.

    Uses the renderer's own block splitting (``subtitles._collect_word_blocks``
    at the template's max_chars/max_duration), so the verdict is about the
    captions that will be burned, not a paraphrase of them. ``karaoke`` is the
    template's reveal mode: word-at-a-time timing is judged differently from a
    block shown at once (see ``review``). Returns the ``review()`` dict, with
    ``clip_start``/``clip_end`` echoed for the log.
    """
    blocks = []
    try:
        import subtitles as _subs
        blocks = _subs._collect_word_blocks(
            transcript, float(clip_start), float(clip_end),
            max_chars=max_chars, max_duration=max_duration) or []
    except Exception:
        blocks = []
    words = flatten_words(transcript)
    text_before, text_after = _context(words, clip_start, clip_end)
    result = review(blocks, text_before=text_before, text_after=text_after,
                    clip_seconds=float(clip_end) - float(clip_start),
                    karaoke=karaoke)
    result["clip"] = [round(float(clip_start), 3), round(float(clip_end), 3)]
    return result


# What to say first when a clip has several problems. The list is ordered by
# what explains the rest: a transcript denser than the audio is the cause, the
# unreadable pacing and the phantom repeats are its symptoms, and an operator
# reading one log line needs the cause.
_ISSUE_PRIORITY = ("impossible_density", "no_speech", "gibberish", "junk_text",
                   "repeated_text", "opens_mid_sentence", "ends_mid_sentence",
                   "too_fast_to_read", "sparse_speech")


def summary(result):
    """One log line describing a verdict: "captions read clean" or the issues."""
    if not result:
        return "caption audit unavailable"
    issues = result.get("issues") or []
    if result.get("ok"):
        st = result.get("stats") or {}
        return (f"captions read clean ({st.get('words', 0)} words, "
                f"{st.get('words_per_sec', 0)}/sec)")
    codes = [i["code"] for i in issues]
    ordered = [c for c in _ISSUE_PRIORITY if c in codes] + \
              [c for c in codes if c not in _ISSUE_PRIORITY]
    lead = next((i for i in issues if i["code"] == ordered[0]), issues[0])
    return (f"captions suspect [{', '.join(ordered)}]: {lead.get('detail', '')}")


def verdict_payload(result):
    """The dict a clip's metadata stores for one audit.

    Every path that captions a clip (selection, the burn in ``auto_caption_clip``,
    ``/api/subtitle``, a recut from the editor) records this same shape, so the UI
    has one thing to read and a re-cut verdict cannot quietly grow keys the
    pipeline never wrote. JSON-safe and small: issue codes plus their one-line
    detail, the numbers behind them, and the range judged.
    """
    if not result:
        return None
    issues = result.get("issues") or []
    return {"ok": bool(result.get("ok")),
            "issues": [i["code"] for i in issues],
            "detail": [i.get("detail", "") for i in issues],
            "stats": result.get("stats") or {},
            "clip": result.get("clip")}


def sentence_boundaries(transcript_words):
    """Index the transcript into sentences: [{'start','end','text'}].

    A sentence runs from the word after the previous terminator to the word
    that carries one. The last sentence may be unterminated — that is the real
    end of the audio, not a missing boundary. Times are absolute.
    """
    sentences = []
    current = []
    for word in transcript_words:
        current.append(word)
        if ends_sentence(word["word"]):
            sentences.append(_sentence(current))
            current = []
    if current:
        sentences.append(_sentence(current))
    return sentences


def _sentence(words):
    return {"start": float(words[0]["start"]),
            "end": float(words[-1]["end"]),
            "text": join_words(words)}


def containing_sentence(sentences, seconds):
    """The sentence holding ``seconds`` (absolute), or None.

    Between sentences (silence) counts as the sentence that just ended, which
    is what a cut placed in a pause should attach to.
    """
    best = None
    for s in sentences:
        if s["start"] - 0.35 <= seconds <= s["end"] + 0.35:
            return s
        if s["start"] <= seconds:
            best = s
    return best


def repair_range(transcript, start, end, video_duration=None,
                 min_duration=15.0, max_duration=60.0, max_shift=6.0):
    """Move a cut onto real sentence boundaries, inside the duration band.

    Returns ``(start, end, notes)``. ``notes`` lists what moved, in plain
    words, so the job log explains a boundary the model did not propose. When
    nothing can move without breaking the band, the input comes back unchanged
    with empty notes: this function has no opinion worth a bad cut, and a
    repaired clip that is too long is not repaired.

    The end is the priority. A clip that opens one word late is a small
    awkwardness; a clip that stops mid-sentence loses the payoff, which is the
    whole reason the clip was chosen. Start moves only backward (earlier), into
    the sentence the cut landed inside, and only while the clip still fits
    ``max_duration``.
    """
    original = (round(float(start), 3), round(float(end), 3))
    s, e = original
    if not enabled():
        return s, e, []
    try:
        words = flatten_words(transcript)
        if not words:
            return s, e, []
        sentences = sentence_boundaries(words)
        if not sentences:
            return s, e, []
        notes = []
        cap = float(video_duration) if video_duration else None

        # --- end: run forward to the end of the sentence being spoken.
        # The last word the cut reaches is the one whose START is still inside
        # (plus a quarter-second of slop). If the cut lands INSIDE that word it
        # chopped speech off even when the word carries a period, so the
        # sentence end is still the target; only a word fully inside the clip
        # and terminating counts as "already finished".
        last_word = None
        for w in words:
            if w["start"] <= e + 0.25:
                last_word = w
            else:
                break
        if last_word is not None:
            chopped = last_word["end"] > e + 0.05
            finished = ends_sentence(last_word["word"]) and not chopped
            if not finished:
                owner = containing_sentence(sentences, last_word["start"])
                if owner and owner["end"] > e:
                    target = owner["end"] if cap is None else min(cap, owner["end"])
                    if (target - e <= max_shift and target - s <= max_duration
                            and target > e):
                        e = float(target)
                        notes.append(f"end {original[1]:.1f}s -> {e:.1f}s "
                                     f"to finish the sentence")

        # --- start: step back to the start of the sentence cut in half.
        first_word = next((w for w in words if w["end"] >= s), None)
        if first_word is not None and not starts_sentence(first_word["word"]):
            owner = containing_sentence(sentences, first_word["start"])
            if owner and owner["start"] < s:
                shift = s - owner["start"]
                new_s = max(0.0, owner["start"])
                if shift <= max_shift and e - new_s <= max_duration and e - new_s >= min_duration:
                    s = new_s
                    notes.append(f"start {original[0]:.1f}s -> {s:.1f}s "
                                 f"to begin the sentence")

        if s == original[0] and e == original[1]:
            return original[0], original[1], []
        return round(s, 3), round(e, 3), notes
    except Exception:
        return original[0], original[1], []
